# ---------------------------------------------------------------- sitemap and robots
def build_sitemap(posts, cities):
    urls = [('/', TODAY, '1.0'), ('/locations/', TODAY, '0.8'), ('/blog/', TODAY, '0.7'), ('/privacy', TODAY, '0.2'), ('/designer', TODAY, '0.9')]
    urls += [(f'/locations/{slug(c)}', TODAY, '0.7') for c in cities]
    urls += [(f'/blog/{p["slug"]}', p['date'], '0.6') for p in posts]
    xml = '<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n'
    xml += ''.join(f'  <url><loc>{SITE}{u}</loc><lastmod>{d}</lastmod><priority>{p}</priority></url>\n' for u, d, p in urls)
    write('sitemap.xml', xml + '</urlset>\n')
    write('robots.txt', f'User-agent: *\nAllow: /\nDisallow: /api/\n\nSitemap: {SITE}/sitemap.xml\n')
    return len(urls)


