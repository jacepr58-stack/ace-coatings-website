def build_blog():
    posts = json.loads((CONTENT / 'blog' / 'posts.json').read_text())
    for p in posts:
        pool = MULTI if 'basketball' in p['slug'] else PICKLE
        p['img'] = pool[h(p['slug']) % len(pool)]
        p['nice'] = datetime.date.fromisoformat(p['date']).strftime('%B %-d, %Y')

    def card(p, hidden=False):
        return (f'<a class="post-card" href="/blog/{p["slug"]}"{" hidden" if hidden else ""}><img src="/img/t/{p["img"][0]}.jpg" alt="{esc(p["img"][1])}" loading="lazy" width="640" height="400">'
                f'<div><time datetime="{p["date"]}">{p["nice"]}</time><h3>{esc(p["title"])}</h3><p>{esc(p["desc"])}</p></div></a>')

